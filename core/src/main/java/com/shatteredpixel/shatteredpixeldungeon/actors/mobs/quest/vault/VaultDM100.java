package com.shatteredpixel.shatteredpixeldungeon.actors.mobs.quest.vault;

import com.shatteredpixel.shatteredpixeldungeon.actors.Char;
import com.shatteredpixel.shatteredpixeldungeon.actors.mobs.DM100;
import com.shatteredpixel.shatteredpixeldungeon.items.quest.DwarfToken;
import com.shatteredpixel.shatteredpixeldungeon.sprites.DM100Sprite;

public class VaultDM100 extends DM100 {

	{
		//reborn 的 dm100.png 没有 4.0 的青绿改装行（4.0 用 DM100Sprite.Vault + texOffset(16)），先用基础贴图
		spriteClass = DM100Sprite.class;

		defenseSkill = 18;

		maxLvl = 30;
		EXP = 0;
		loot = DwarfToken.class;
		lootChance = 1;
	}

	@Override
	public int attackSkill( Char target ) {
		return 25;
	}

	@Override
	public int drRoll() {
		//提升 DR 以抵消英雄高 HP 和溢出力量带来的额外伤害
		return super.drRoll() + 4;
	}
}
